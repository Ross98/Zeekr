// Catches duplicate cross-day energy, timezone drift, and lost month/range boundaries.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const window={};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'../zeekr_control/static/parking.js'),'utf8'),{window,Intl,Date,Number});
assert.equal(typeof window.ParkingPage.calendarModel,'function','parking needs a calendar model');
const model=window.ParkingPage.calendarModel;
const event={id:'cross',start_time:Date.parse('2026-09-30T23:00:00+08:00'),end_time:Date.parse('2026-10-01T01:00:00+08:00'),soc_drop:2,estimated_kwh:1.5};
const result=model([event],'2026-09-29','2026-10-02');
assert.equal(JSON.stringify(result.months),JSON.stringify(['2026-09','2026-10']));
assert.equal(result.month,'2026-09');
assert.equal(result.offset,1,'September starts on Tuesday');
assert.equal(result.days.length,30);
assert.equal(result.days.find(d=>d.date==='2026-09-30').rows[0].full,false);
assert.equal(result.days.find(d=>d.date==='2026-09-29').rows.length,0);
assert.equal(result.days[0].inRange,false);
const october=model([event],'2026-09-29','2026-10-02','2026-10');
assert.equal(october.days.find(d=>d.date==='2026-10-01').rows[0].full,true);
assert.equal(october.days.find(d=>d.date==='2026-10-02').rows.length,0);
assert.equal(october.days.find(d=>d.date==='2026-10-03').inRange,false);
assert.equal(model([event],'2026-09-30','2026-09-30').days.flatMap(d=>d.rows).filter(r=>r.full).length,0,'end outside range must not be assigned to a visible earlier day');
const many=Array.from({length:5},(_,i)=>({...event,id:String(i),start_time:Date.parse('2026-10-01T02:00:00+08:00')+i*3600000,end_time:Date.parse('2026-10-01T02:30:00+08:00')+i*3600000}));
assert.equal(model(many,'2026-10-01','2026-10-01').days[0].rows.length,5,'model must retain every record for expansion');
assert.equal(model([],'2026-02-01','2026-02-28').days.length,28);
assert.equal(model([],'2028-02-01','2028-02-29').days.length,29);
assert.equal(model([],'2026-10-01','2026-10-01','stale').month,'2026-10');
assert.equal(window.ParkingPage.durationLabel(30),'不足1分');
assert.equal(window.ParkingPage.durationLabel(30060),'8小时21分');
assert.equal(window.ParkingPage.durationLabel(190800),'2天5小时');
