const assert=require('node:assert/strict');
const V=require('../zeekr_control/static/local-trip-visuals.js');
const gapSummary=V.summary({summary:{trip_count:0,pending_mileage_km:26},coverage:{coverage:'observed'}},'2026-10-28');
assert.match(gapSummary,/中断待核对里程/);
assert.match(gapSummary,/26/);
assert.match(gapSummary,/实际行驶日期、起止时间和趟数未知/);
const at=value=>Date.parse('2026-10-'+value+'+08:00');
const place=(key,label=key)=>({key,label,source:'manual',issues:[]});
const trip=(id,a,b,start,end)=>({id,type:'trip',start_time:at(start),end_time:at(end),start_place:place(a),end_place:place(b),distance_km:10,duration_seconds:600});
const first=trip('a','home','work','20T08:00:00','20T08:30:00'),last=trip('b','work','home','20T18:00:00','20T18:30:00');
let model=V.chainModel([first,last]);
assert.equal(model.filter(x=>x.kind==='place').length,3);
assert.equal(model.filter(x=>x.kind==='parking').length,0,'never infer parking from a trip gap');
assert.equal(model.find(x=>x.kind==='place'&&x.place.key==='work').depart_time,last.start_time);
assert.ok(model.some(x=>x.kind==='gap'),'unobserved interval remains explicit');
last.start_place=place('other','work');
assert.equal(V.chainModel([first,last]).filter(x=>x.kind==='place').length,4,'same names do not merge different keys');
const unknown={...first,start_place:place(null,'unknown'),end_place:place(null,'unknown')};
assert.equal(V.chainModel([unknown,{...unknown,id:'c'}]).filter(x=>x.kind==='place').length,4);
const cross=trip('cross','a','b','19T23:50:00','20T00:20:00');
const segments=V.daySegments([cross,first,{...last,start_time:null}],'2026-10-20');
assert.equal(segments.length,2);
assert.equal(segments[0].start_minute,0);
assert.equal(segments[0].end_minute,20);
assert.equal(segments[0].clipped,true);
assert.equal(V.daySegments([cross],'2026-10-19')[0].end_minute,1440);
assert.deepEqual(V.daySegments([{...first,start_time:NaN}],'2026-10-20'),[]);
assert.equal(V.duration(3600),'1 小时');
assert.equal(V.duration(null),'未知');
assert.match(V.summary({summary:{actual_cents:1234},coverage:{}},'2026-10-20'),/12.34 元/);
assert.match(V.clockChart([first,{...first,id:'duplicate'}],'2026-10-20','day'),/30 分钟/);
assert.doesNotMatch(V.clockChart([first,{...first,id:'duplicate'}],'2026-10-20','day'),/1 小时/);
const referenceParking={id:'ref',type:'parking',start_time:first.end_time,end_time:last.start_time,end_place:place('work'),end_place_evidence:{source:'parking_reference'},parking_status:'parked',observation_quality:{unknown_seconds:3600}};
assert.match(V.chain([referenceParking],'day','2026-10-20'),/推定地点/);
assert.match(V.chain([referenceParking],'day','2026-10-20'),/缺口 1 小时/);
console.log('Local trip chain model passed.');
